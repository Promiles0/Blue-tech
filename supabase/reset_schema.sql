create policy "public read categories" on public.categories for select using (true);
create policy "public read products" on public.products for select using (true);
create policy "read own users row" on public.users for select using (auth.uid() = id);
create policy "update own users row" on public.users for update using (auth.uid() = id) with check (auth.uid() = id);
create policy "read own profile row" on public.profiles for select using (auth.uid() = id);
create policy "read own orders" on public.orders for select using (auth.uid() = user_id);
create policy "manage own cart" on public.cart for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "manage own wishlist" on public.wishlist for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "public read reviews" on public.reviews for select using (true);
create policy "manage own reviews" on public.reviews for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "read own notifications" on public.notifications for select using (auth.uid() = user_id);
create policy "update own notifications" on public.notifications for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Promote the existing Auth account. This does not create a password.
