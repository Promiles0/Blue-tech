-- Public product images. Uploads are performed by the admin-only Edge Function.
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

-- Profile rows are created automatically for new Auth accounts.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.users (id, email, name, role)
  values (new.id, coalesce(new.email, ''), new.raw_user_meta_data ->> 'name', 'user');
  insert into public.profiles (id, email, role)
  values (new.id, coalesce(new.email, ''), 'USER');
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- RLS for direct Supabase client access. The Edge Function uses its own guards.
alter table public.users enable row level security;
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.cart enable row level security;
