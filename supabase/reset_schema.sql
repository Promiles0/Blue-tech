create table public.wishlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.users(id) on delete cascade
);

create table public.wishlist_items (
  id bigint generated by default as identity primary key,
  wishlist_id bigint not null references public.wishlists(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  added_at timestamptz not null default now(),
  unique (wishlist_id, product_id)
);

create table public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  product_id bigint references public.products(id) on delete restrict,
  quantity integer check (quantity > 0),
  address_id bigint references public.addresses(id) on delete restrict,
  total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
  status text not null default 'pending' check (status in ('pending','paid','processing','shipped','delivered','cancelled')),
  shipping_method text,
  payment_method text,
  shipping_fee numeric(12,2) not null default 0,
