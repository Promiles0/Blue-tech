-- Blue-Tech consolidated Supabase schema
-- Run this in the NEW Supabase project's SQL Editor.
-- Supabase Auth owns passwords. Never store a plaintext password in password_hash.
-- The admin bootstrap at the bottom promotes the Auth user with the configured email.

create extension if not exists pgcrypto;

-- Core identity and catalog tables
create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  password_hash text,
  name text,
  phone text,
  picture text,
  provider text,
  provider_id text,
  role text not null default 'user' check (role in ('admin', 'user')),
  is_suspended boolean not null default false,
  created_at timestamptz not null default now(),
  last_login timestamptz
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  role text not null default 'USER' check (role in ('ADMIN', 'USER')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  parent_id bigint references public.categories(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Upgrade an existing categories table created before parent categories were added.
alter table public.categories add column if not exists parent_id bigint;
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'categories_parent_id_fkey'
      and conrelid = 'public.categories'::regclass
  ) then
    alter table public.categories
      add constraint categories_parent_id_fkey
      foreign key (parent_id) references public.categories(id) on delete set null;
  end if;
end
$$;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  name text not null,
  description text,
  price numeric(12,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  average_rating numeric(3,2) not null default 0 check (average_rating between 0 and 5),
  review_count integer not null default 0 check (review_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.product_variants (
