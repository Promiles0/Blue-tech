-- Admin bootstrap. Create this email first in Authentication > Users and set its
-- password there. This statement promotes that Auth identity immediately.
insert into public.users (id, email, role)
select id, email, 'admin'
from auth.users
where lower(email) = lower('systemadmin@ecom.rw')
on conflict (id) do update set role = 'admin';

insert into public.profiles (id, email, role)
select id, email, 'ADMIN'
from auth.users
where lower(email) = lower('systemadmin@ecom.rw')
on conflict (id) do update set role = 'ADMIN';

-- Verify the bootstrap found an Auth user before attempting login.
do $$
begin
  if not exists (select 1 from auth.users where lower(email) = lower('systemadmin@ecom.rw')) then
    raise notice 'Create systemadmin@ecom.rw in Authentication > Users, then rerun the admin bootstrap insert above.';
  end if;
end
$$;
