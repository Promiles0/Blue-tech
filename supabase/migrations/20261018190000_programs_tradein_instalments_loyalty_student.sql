alter table public.users add column if not exists loyalty_points integer not null default 0 check (loyalty_points >= 0);
alter table public.users add column if not exists student_verified_until date;

alter table public.orders add column if not exists points_used integer not null default 0;
alter table public.orders add column if not exists points_discount numeric(14,2) not null default 0;
alter table public.orders add column if not exists student_discount numeric(14,2) not null default 0;
alter table public.orders add column if not exists points_awarded boolean not null default false;

create table if not exists public.points_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  order_id bigint references public.orders(id) on delete set null,
  delta integer not null,
  reason text not null,          -- earned | redeemed | refunded | adjusted
  created_at timestamptz not null default now()
);
create index if not exists points_ledger_user_idx on public.points_ledger (user_id, created_at desc);

create table if not exists public.trade_in_requests (
  id bigint generated by default as identity primary key,
  user_id uuid,
  name text not null,
  phone text not null,
  email text,
  device_type text not null,
  brand text,
  model text,
  age_years integer,
  condition text not null check (condition in ('excellent', 'good', 'fair', 'broken')),
  estimate_low numeric(14,2),
  estimate_high numeric(14,2),
  notes text,
  status text not null default 'new' check (status in ('new', 'contacted', 'accepted', 'declined')),
  created_at timestamptz not null default now()
);

create table if not exists public.instalment_requests (
  id bigint generated by default as identity primary key,
  user_id uuid,
  name text not null,
  phone text not null,
  email text,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  price numeric(14,2) not null,
  months integer not null,
  deposit numeric(14,2) not null,
  monthly numeric(14,2) not null,
  notes text,
  status text not null default 'new' check (status in ('new', 'contacted', 'approved', 'declined')),
  created_at timestamptz not null default now()
);

create table if not exists public.student_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  school text not null,
  school_email text not null,
  status text not null default 'new' check (status in ('new', 'approved', 'declined')),
  created_at timestamptz not null default now()
);

alter table public.points_ledger enable row level security;
alter table public.trade_in_requests enable row level security;
alter table public.instalment_requests enable row level security;
alter table public.student_requests enable row level security;
