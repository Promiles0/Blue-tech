-- Round 3 (8b, 8c): a record of each backup run (written by scripts/backup-db.ps1), so
-- Admin → Settings can show "Last backup" and the hourly job can warn when it's overdue.
create table if not exists public.backup_log (
  id bigint generated by default as identity primary key,
  ran_at timestamptz not null default now(),
  ok boolean not null,
  db_bytes bigint,
  files integer,
  note text
);
create index if not exists backup_log_ran_at_idx on public.backup_log (ran_at desc);
alter table public.backup_log enable row level security;
