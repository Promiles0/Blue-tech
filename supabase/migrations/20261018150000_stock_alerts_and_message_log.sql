-- Back-in-stock requests and a log of customer messages (email / SMS / WhatsApp).
-- Messages only go out once a provider key is configured; until then they're logged as
-- "skipped" so the admin can see what would have been sent.

create table if not exists public.stock_alerts (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  email text,
  phone text,
  lang text not null default 'en',
  user_id uuid,
  created_at timestamptz not null default now(),
  notified_at timestamptz,
  constraint stock_alerts_contact check (email is not null or phone is not null)
);

create index if not exists stock_alerts_pending_idx on public.stock_alerts (product_id) where notified_at is null;
-- One pending request per contact per product.
create unique index if not exists stock_alerts_unique_email on public.stock_alerts (product_id, lower(email)) where notified_at is null and email is not null;
create unique index if not exists stock_alerts_unique_phone on public.stock_alerts (product_id, phone) where notified_at is null and phone is not null;

alter table public.stock_alerts enable row level security;

create table if not exists public.message_log (
  id bigint generated by default as identity primary key,
  channel text not null check (channel in ('email', 'sms', 'whatsapp')),
  recipient text not null,
  kind text not null,            -- e.g. order_status, stock_alert, quote_confirmation
  status text not null check (status in ('sent', 'failed', 'skipped')),
  detail text,                   -- provider error or "not configured"
  created_at timestamptz not null default now()
);

create index if not exists message_log_created_idx on public.message_log (created_at desc);
alter table public.message_log enable row level security;
