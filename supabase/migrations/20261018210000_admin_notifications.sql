-- Admin notifications: shop events for the team (new order, payment, quote, review, low
-- stock…), kept apart from customers' own notifications. Previously the admin bell read —
-- and "mark all read" cleared — every customer's notifications.
create table if not exists public.admin_notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  body text,
  severity text not null default 'info' check (severity in ('info', 'success', 'warning', 'error')),
  category text not null default 'system' check (category in ('order', 'business', 'community', 'shopping', 'account', 'system', 'security')),
  href text,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists admin_notifications_created_idx on public.admin_notifications (created_at desc);
create index if not exists admin_notifications_unread_idx on public.admin_notifications (read) where read = false;

alter table public.admin_notifications enable row level security;
