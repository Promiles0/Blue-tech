-- Blue (AI assistant) conversation log for the admin insights page, a private admin note
-- on quote requests, and an admin-editable instructions setting for Blue.

create table if not exists public.chat_logs (
  id bigint generated by default as identity primary key,
  -- Random id the widget keeps per browser tab session; groups turns into a conversation.
  -- Not linked to a user account.
  session_id text not null,
  question text not null,
  reply text not null,
  product_ids bigint[] not null default '{}',
  handoff text not null default 'none' check (handoff in ('none', 'quote', 'human')),
  -- Blue's own judgement that the customer wanted something the catalogue doesn't carry.
  no_match boolean not null default false,
  -- Short topic label from Blue (e.g. "laptops", "delivery") for grouping top questions.
  topic text,
  created_at timestamptz not null default now()
);

create index if not exists chat_logs_created_at_idx on public.chat_logs (created_at desc);
create index if not exists chat_logs_session_idx on public.chat_logs (session_id, created_at);

-- Only the edge function (service role) reads or writes this table.
alter table public.chat_logs enable row level security;

alter table public.quote_requests add column if not exists admin_note text;

insert into public.site_settings (key, value, is_public)
values ('blue_instructions', '', false)
on conflict (key) do nothing;
