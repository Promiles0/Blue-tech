-- Round 4 (6b, 6c): timed sale campaigns and "buy together and save" bundles.
create table if not exists public.campaigns (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique check (slug ~ '^[a-z0-9-]{2,60}$'),
  kind text not null check (kind in ('percent', 'fixed')),
  value numeric not null check (value > 0),
  target text not null default 'all' check (target in ('all', 'category', 'products')),
  category_id bigint references public.categories(id) on delete set null,
  product_ids bigint[] not null default '{}',
  starts_at timestamptz not null,
  ends_at timestamptz not null check (ends_at > starts_at),
  is_active boolean not null default true,
  banner_text text,
  created_at timestamptz not null default now()
);
create index if not exists campaigns_window_idx on public.campaigns (is_active, starts_at, ends_at);
alter table public.campaigns enable row level security;

create table if not exists public.bundles (
  id bigint generated by default as identity primary key,
  name text not null,
  product_ids bigint[] not null check (cardinality(product_ids) between 2 and 5),
  saving numeric not null check (saving > 0),          -- RWF off per complete bundle
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.bundles enable row level security;

-- What the shopper saved on an order, for invoices and Sales insights.
alter table public.orders add column if not exists campaign_discount numeric not null default 0;
alter table public.orders add column if not exists bundle_discount numeric not null default 0;
