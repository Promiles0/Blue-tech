-- Site errors (8a): crashes in customers' browsers and unexpected server errors, grouped by
-- a fingerprint so one bug is one row with a count. Shown on Admin → Site errors.
create table if not exists public.client_errors (
  id bigint generated by default as identity primary key,
  fingerprint text not null unique,
  source text not null default 'client' check (source in ('client', 'server')),
  message text not null,
  stack text,
  url text,
  user_agent text,
  release text,
  count integer not null default 1,
  status text not null default 'open' check (status in ('open', 'fixed')),
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now()
);
create index if not exists client_errors_last_seen_idx on public.client_errors (last_seen desc);
alter table public.client_errors enable row level security;
