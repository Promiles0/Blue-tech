-- Round 4 (3d): customers ask about a product; staff answer; answers show on the product page
-- (and Blue learns them). Only answered questions are public.
create table if not exists public.product_questions (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id uuid references public.users(id) on delete set null,
  question text not null check (char_length(question) between 5 and 500),
  answer text,
  answered_by text,
  answered_at timestamptz,
  status text not null default 'pending' check (status in ('pending', 'answered', 'hidden')),
  created_at timestamptz not null default now()
);
create index if not exists product_questions_product_idx on public.product_questions (product_id, status);
create index if not exists product_questions_status_idx on public.product_questions (status, created_at desc);
alter table public.product_questions enable row level security;
