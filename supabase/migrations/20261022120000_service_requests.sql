-- Round 3 (5b + 5c): returns and warranty claims, raised by customers from a delivered order
-- and handled on Admin → Returns & warranty. Photos live in a PRIVATE bucket (they can show
-- serial numbers or receipts); admins and the customer see them through short-lived links.
create table if not exists public.service_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  variant_id bigint,
  product_name text,
  quantity integer not null default 1 check (quantity > 0),
  type text not null check (type in ('return', 'warranty')),
  reason text not null,
  details text,
  photos text[] not null default '{}',          -- storage paths in service-photos
  status text not null default 'new'
    check (status in ('new', 'approved', 'received', 'repaired', 'replaced', 'refunded', 'rejected', 'closed')),
  customer_message text,                        -- latest note to the customer (instructions, reason)
  refund_amount numeric,
  refund_method text,
  restocked boolean not null default false,
  history jsonb not null default '[]',          -- [{ at, status, by, message }]
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists service_requests_order_idx on public.service_requests (order_id);
create index if not exists service_requests_user_idx on public.service_requests (user_id);
create index if not exists service_requests_status_idx on public.service_requests (status, created_at desc);
alter table public.service_requests enable row level security;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('service-photos', 'service-photos', false, 3145728, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;
