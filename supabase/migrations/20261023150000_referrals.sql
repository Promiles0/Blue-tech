-- Round 4 (6d): refer a friend. The friend gets money off their first order; when that order
-- is paid the referrer gets a personal one-time coupon. Off until switched on in Programs.
alter table public.users add column if not exists referral_code text unique;

create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  referrer_id uuid not null references public.users(id) on delete cascade,
  referee_id uuid not null references public.users(id) on delete cascade,
  order_id bigint references public.orders(id) on delete set null,
  discount numeric not null default 0,
  status text not null default 'pending' check (status in ('pending', 'rewarded')),
  reward_code text,                                  -- the referrer's coupon code
  created_at timestamptz not null default now(),
  rewarded_at timestamptz,
  check (referrer_id <> referee_id)
);
create index if not exists referrals_referrer_idx on public.referrals (referrer_id, created_at desc);
create index if not exists referrals_referee_idx on public.referrals (referee_id);
create index if not exists referrals_order_idx on public.referrals (order_id);
alter table public.referrals enable row level security;

-- A coupon can belong to one customer (the referrer's reward); null = anyone can use it.
alter table public.coupons add column if not exists user_id uuid references public.users(id) on delete cascade;

alter table public.orders add column if not exists referral_discount numeric not null default 0;
